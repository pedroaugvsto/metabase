import fs from "node:fs";
import path from "node:path";

import { load as parseYaml } from "js-yaml";

import { DATA_APP_MANIFEST_FILE_NAME } from "../data-app-dev/constants/paths";

import { isEntityId } from "./entity-ids";
import { isRecord } from "./guards";

export const MANIFEST_FILE = DATA_APP_MANIFEST_FILE_NAME;

export interface AppManifest {
  name: string;
  collection?: string;
}

export function readManifest(appRoot: string): AppManifest {
  const manifestPath = path.join(appRoot, MANIFEST_FILE);

  if (!fs.existsSync(manifestPath)) {
    throw new Error(`${MANIFEST_FILE} is missing from ${appRoot}.`);
  }

  const manifest: unknown = parseYaml(fs.readFileSync(manifestPath, "utf8"));

  if (!isRecord(manifest) || typeof manifest.name !== "string") {
    throw new Error(`${MANIFEST_FILE} must declare a "name".`);
  }

  if (manifest.collection !== undefined && !isEntityId(manifest.collection)) {
    throw new Error(
      `${MANIFEST_FILE} has an invalid "collection". Remove it and run \`npm run sync-resources\` to create a new one.`,
    );
  }

  return { name: manifest.name, collection: manifest.collection };
}

const parsedCollection = (contents: string) => {
  try {
    const manifest: unknown = parseYaml(contents);
    return isRecord(manifest) ? manifest.collection : undefined;
  } catch {
    return undefined;
  }
};

/**
 * The manifest's text with `collection` appended. Appended as text, since
 * dumping the parsed YAML would drop the file's comments, and checked before
 * anything is written, since a manifest in flow style can't take the line.
 */
export function manifestWithCollection(appRoot: string, collection: string) {
  const contents = fs.readFileSync(path.join(appRoot, MANIFEST_FILE), "utf8");
  const separator = contents.endsWith("\n") || contents === "" ? "" : "\n";
  const next = `${contents}${separator}\n# The app's resource collection. Generated by \`npm run sync-resources\`; never edit it.\ncollection: ${collection}\n`;

  if (parsedCollection(next) !== collection) {
    throw new Error(
      `Could not add "collection" to ${MANIFEST_FILE}. Write it in block style, one key per line, and run sync-resources again.`,
    );
  }

  return next;
}

export function writeManifest(appRoot: string, contents: string) {
  fs.writeFileSync(path.join(appRoot, MANIFEST_FILE), contents);
}
